import { createDatabase } from "../src/db/index.js";
import { requireUnpooledDatabaseUrl } from "../src/db/migration-url.js";
import { saveRootCredential } from "../src/db/root-credential-file.js";
import { initializeRoot } from "../src/root-account.js";

async function main(): Promise<void> {
  if (process.argv.length > 2) throw new Error("Arguments are not accepted.");
  const db = createDatabase(requireUnpooledDatabaseUrl(process.env));
  try {
    const created = await initializeRoot(db, async (password) => {
      const path = process.env.ROOT_PASSWORD_FILE;
      if (!path) throw new Error("ROOT_PASSWORD_FILE is required for a new account.");
      await saveRootCredential(path, password);
    });
    process.stdout.write(created
      ? "Root created. Retrieve the generated password from your private ROOT_PASSWORD_FILE.\n"
      : "Root already exists. Its password was not changed. Any file generated by this concurrent run contains an unused candidate password.\n");
  } finally {
    await db.close?.();
  }
}

main().catch(() => {
  // Do not print database errors/URLs, credentials, or arbitrary filesystem
  // errors into Render logs. A candidate credential file may have been written
  // before a DB failure or concurrent initializer; keep it until verified.
  process.stderr.write("Root initialization failed. Check the direct database connection, reserved account conflicts, and an unused absolute ROOT_PASSWORD_FILE outside the checkout. Any generated file may contain an unused candidate password; verify login before retaining it.\n");
  process.exitCode = 1;
});
